#!/bin/bash

# Проверяем, что аргументы вообще есть
if [ $# -eq 0 ]; then
    echo "Ошибка: не переданы аргументы"
    echo "Использование: $0 <число1> <число2> ..."
    exit 1
fi

# Количество аргументов
count=$#
echo "Количество чисел: $count"

# Считаем сумму всех аргументов
sum=0
for num in "$@"; do
    sum=$((sum + num))
done

# Среднее арифметическое (целое)
average=$((sum / count))
echo "Среднее арифметическое: $average"